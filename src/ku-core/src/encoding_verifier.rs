//! # Encoding Verifier — 2-Phase Verification for Encoding Consensus
//!
//! Provides tools to verify that a CoreDna encoding correctly represents
//! the original raw text knowledge.
//!
//! ## Phase A: AI Decomposition Verification
//! Compares two AI-generated CoreDna encodings for semantic agreement:
//! - Same gene_type?
//! - Similar opcodes/instruction types?
//! - Overlapping concept IDs?
//!
//! ## Phase B: Tool Encoding Verification
//! Checks that the binary encode/decode pipeline works correctly:
//! - Round-trip: encode → decode → should match original
//! - CRC integrity
//! - CID computation consistency

use crate::core_dna::{CoreDna, Instruction, encode_core_dna, decode_core_dna};
use crate::types::ConceptId;
use std::collections::HashSet;

// ═══════════════════════════════════════════════════════════════════════════
// Phase A: Decomposition Verification
// ═══════════════════════════════════════════════════════════════════════════

/// Result of an AI's decomposition of raw text into structured instructions.
#[derive(Debug, Clone)]
pub struct DecompositionResult {
    /// Gene type chosen by this AI.
    pub gene_type: u8,

    /// Instructions generated by this AI.
    pub instructions: Vec<Instruction>,

    /// All concept IDs referenced.
    pub concept_ids: Vec<ConceptId>,

    /// AI's self-reported confidence (0.0-1.0).
    pub confidence: f32,
}

impl DecompositionResult {
    /// Extract from a CoreDna.
    pub fn from_core_dna(dna: &CoreDna) -> Self {
        let concept_ids = extract_concept_ids(&dna.instructions);
        Self {
            gene_type: dna.header.gene_type,
            instructions: dna.instructions.clone(),
            concept_ids,
            confidence: 1.0, // Default: full confidence
        }
    }
}

/// Compute semantic agreement between two decomposition results.
///
/// Returns a score in [0.0, 1.0]:
/// - 0.3 weight: gene_type match
/// - 0.3 weight: opcode type overlap (Jaccard similarity)
/// - 0.4 weight: concept ID overlap (Jaccard similarity)
pub fn decomposition_agreement(a: &DecompositionResult, b: &DecompositionResult) -> f32 {
    let mut score = 0.0;

    // Factor 1: Gene type match (0.3)
    if a.gene_type == b.gene_type {
        score += 0.3;
    }

    // Factor 2: Opcode type overlap (0.3)
    let opcodes_a: HashSet<u8> = a.instructions.iter()
        .map(|i| instruction_opcode(i))
        .collect();
    let opcodes_b: HashSet<u8> = b.instructions.iter()
        .map(|i| instruction_opcode(i))
        .collect();
    let opcode_sim = jaccard_similarity(&opcodes_a, &opcodes_b);
    score += 0.3 * opcode_sim;

    // Factor 3: Concept ID overlap (0.4)
    let concepts_a: HashSet<ConceptId> = a.concept_ids.iter().copied().collect();
    let concepts_b: HashSet<ConceptId> = b.concept_ids.iter().copied().collect();
    let concept_sim = jaccard_u64_similarity(&concepts_a, &concepts_b);
    score += 0.4 * concept_sim;

    score
}

/// Compute agreement between two CoreDna directly.
pub fn core_dna_agreement(a: &CoreDna, b: &CoreDna) -> f32 {
    let da = DecompositionResult::from_core_dna(a);
    let db = DecompositionResult::from_core_dna(b);
    decomposition_agreement(&da, &db)
}

// ═══════════════════════════════════════════════════════════════════════════
// Phase B: Tool Encoding Verification
// ═══════════════════════════════════════════════════════════════════════════

/// Result of tool encoding verification.
#[derive(Debug, Clone, PartialEq)]
pub enum ToolVerifyResult {
    /// Encoding round-trip passed — binary is correct.
    Pass,
    /// Round-trip failed — the tool may be tampered with.
    Fail(String),
}

/// Verify that a CoreDna can be correctly encoded and decoded (round-trip).
///
/// This checks that the binary serialization pipeline is not corrupted:
/// 1. Encode CoreDna → bytes
/// 2. Decode bytes → CoreDna'
/// 3. Verify CoreDna' == CoreDna (structurally identical)
///
/// If this fails, the encoding tool itself may be tampered with.
pub fn tool_encoding_check(dna: &CoreDna) -> ToolVerifyResult {
    // Step 1: Encode
    let encoded = match encode_core_dna(dna) {
        Ok(bytes) => bytes,
        Err(e) => return ToolVerifyResult::Fail(format!("Encode failed: {}", e)),
    };

    // Step 2: Decode
    let decoded = match decode_core_dna(&encoded) {
        Ok(d) => d,
        Err(e) => return ToolVerifyResult::Fail(format!("Decode failed: {}", e)),
    };

    // Step 3: Structural comparison
    if decoded.header != dna.header {
        return ToolVerifyResult::Fail(format!(
            "Header mismatch: gene_type {} vs {}",
            decoded.header.gene_type, dna.header.gene_type
        ));
    }

    if decoded.instructions.len() != dna.instructions.len() {
        return ToolVerifyResult::Fail(format!(
            "Instruction count mismatch: {} vs {}",
            decoded.instructions.len(), dna.instructions.len()
        ));
    }

    if decoded != *dna {
        return ToolVerifyResult::Fail("Instruction content mismatch after round-trip".into());
    }

    ToolVerifyResult::Pass
}

