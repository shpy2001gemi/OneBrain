/// Extract all concept IDs from an instruction list.
fn extract_concept_ids(instructions: &[Instruction]) -> Vec<ConceptId> {
    let mut ids = Vec::new();
    for inst in instructions {
        match inst {
            Instruction::Triple { s, p, o } => { ids.push(*s); ids.push(*p); ids.push(*o); },
            Instruction::Quality { s, q } => { ids.push(*s); ids.push(*q); },
            Instruction::Quantity { s, unit, .. } => { ids.push(*s); ids.push(*unit); },
            Instruction::Sequence { items } => ids.extend(items),
            Instruction::PartOf { part, whole } => { ids.push(*part); ids.push(*whole); },
            Instruction::Located { s, location } => { ids.push(*s); ids.push(*location); },
            Instruction::Temporal { s, time } => { ids.push(*s); ids.push(*time); },
            Instruction::Causal { cause, effect } => { ids.push(*cause); ids.push(*effect); },
            Instruction::Simulates { s, model } => { ids.push(*s); ids.push(*model); },
            Instruction::Condition { cond, result } => { ids.push(*cond); ids.push(*result); },
            Instruction::Agent { actor, action } => { ids.push(*actor); ids.push(*action); },
            Instruction::Tool { action, instrument } => { ids.push(*action); ids.push(*instrument); },
            Instruction::Range { s, .. } => { ids.push(*s); },
            Instruction::Tolerance { s, .. } => { ids.push(*s); },
            Instruction::Constraint { source, target, .. } => { ids.push(*source); ids.push(*target); },
            Instruction::EnumVal { s, values } => { ids.push(*s); ids.extend(values); },
            Instruction::Step { action, target, .. } => { ids.push(*action); ids.push(*target); },
            Instruction::Precond { concept } => ids.push(*concept),
            Instruction::Effect { concept } => ids.push(*concept),
            Instruction::Label { key, value } => { ids.push(*key); ids.push(*value); },
            Instruction::Member { label, .. } => { ids.push(*label); },
            // Non-concept instructions
            Instruction::Certainty { .. }
            | Instruction::Difficulty { .. }
            | Instruction::CidRef { .. }
            | Instruction::Affect { .. }
            | Instruction::TextRef { .. }
            | Instruction::Formula { .. }
            | Instruction::Witness { .. }
            | Instruction::MediaRef { .. }
            | Instruction::CompositeHdr { .. }
            | Instruction::End => {},
        }
    }
    ids.sort_unstable();
    ids.dedup();
    ids
}

/// Get the opcode number for an instruction (for similarity comparison).
fn instruction_opcode(inst: &Instruction) -> u8 {
    match inst {
        Instruction::Triple { .. } => 0x00,
        Instruction::Quality { .. } => 0x01,
        Instruction::Quantity { .. } => 0x02,
        Instruction::Sequence { .. } => 0x03,
        Instruction::PartOf { .. } => 0x04,
        Instruction::Located { .. } => 0x05,
        Instruction::Temporal { .. } => 0x06,
        Instruction::Causal { .. } => 0x07,
        Instruction::Simulates { .. } => 0x08,
        Instruction::Condition { .. } => 0x09,
        Instruction::Agent { .. } => 0x0A,
        Instruction::Tool { .. } => 0x0B,
        Instruction::Range { .. } => 0x0C,
        Instruction::Tolerance { .. } => 0x0D,
        Instruction::Constraint { .. } => 0x0E,
        Instruction::EnumVal { .. } => 0x0F,
        Instruction::Certainty { .. } => 0x10,
        Instruction::Difficulty { .. } => 0x11,
        Instruction::CidRef { .. } => 0x12,
        Instruction::Step { .. } => 0x13,
        Instruction::Precond { .. } => 0x14,
        Instruction::Effect { .. } => 0x15,
        Instruction::Affect { .. } => 0x16,
        Instruction::Label { .. } => 0x17,
        Instruction::TextRef { .. } => 0x18,
        Instruction::Formula { .. } => 0x19,
        Instruction::Witness { .. } => 0x1A,
        Instruction::MediaRef { .. } => 0x1B,
        Instruction::CompositeHdr { .. } => 0x1C,
        Instruction::Member { .. } => 0x1D,
        Instruction::End => 0x1E,
    }
}

/// Jaccard similarity between two sets of u8.
fn jaccard_similarity(a: &HashSet<u8>, b: &HashSet<u8>) -> f32 {
    if a.is_empty() && b.is_empty() {
        return 1.0;
    }
    let intersection = a.intersection(b).count();
    let union = a.union(b).count();
    if union == 0 { 1.0 } else { intersection as f32 / union as f32 }
}

/// Jaccard similarity between two sets of u64 (ConceptId).
fn jaccard_u64_similarity(a: &HashSet<u64>, b: &HashSet<u64>) -> f32 {
    if a.is_empty() && b.is_empty() {
        return 1.0;
    }
    let intersection = a.intersection(b).count();
    let union = a.union(b).count();
    if union == 0 { 1.0 } else { intersection as f32 / union as f32 }
}

